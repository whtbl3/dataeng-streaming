"""Static world: depots and vans. Single source of truth for the order database seed."""

from __future__ import annotations

from dataclasses import dataclass


@dataclass(frozen=True)
class Depot:
    depot_id: str
    name: str
    lat: float
    lon: float


@dataclass(frozen=True)
class Van:
    van_id: str  # equals the GPS vehicle_id
    depot_id: str
    plate: str
    capacity: int


DEPOTS: tuple[Depot, ...] = (
    Depot("DEP-01", "District 1 Hub", 10.7760, 106.7000),
    Depot("DEP-02", "Tan Binh Hub", 10.8010, 106.6520),
    Depot("DEP-03", "Thu Duc Hub", 10.8490, 106.7720),
    Depot("DEP-04", "District 7 Hub", 10.7330, 106.7220),
)

VAN_COUNT = 200
VAN_CAPACITY = 30

VANS: tuple[Van, ...] = tuple(
    Van(
        van_id=f"VAN-{i:04d}",
        depot_id=DEPOTS[(i - 1) % len(DEPOTS)].depot_id,
        plate=f"51C-{100 + i:03d}.{(i * 37) % 100:02d}",
        capacity=VAN_CAPACITY,
    )
    for i in range(1, VAN_COUNT + 1)
)

DEPOT_BY_ID = {d.depot_id: d for d in DEPOTS}


def _q(text: str) -> str:
    return "'" + text.replace("'", "''") + "'"


def seed_sql() -> str:
    """Idempotent seed statements for depots and vans."""
    depots = ",\n".join(f"  ({_q(d.depot_id)}, {_q(d.name)}, {d.lat}, {d.lon})" for d in DEPOTS)
    vans = ",\n".join(
        f"  ({_q(v.van_id)}, {_q(v.depot_id)}, {_q(v.plate)}, {v.capacity})" for v in VANS
    )
    return (
        "-- Generated by `python -m simulator seed-sql` from simulator/world.py. Do not edit.\n"
        "INSERT INTO depots (depot_id, name, lat, lon) VALUES\n"
        f"{depots}\nON CONFLICT DO NOTHING;\n\n"
        "INSERT INTO vans (van_id, depot_id, plate, capacity) VALUES\n"
        f"{vans}\nON CONFLICT DO NOTHING;\n"
    )
