"""Shared GPS types and constants.

The random walk from spec 001 was replaced in spec 002: vans now follow their delivery
routes, generated by `simulator.day`.
"""

from __future__ import annotations

from dataclasses import dataclass
from datetime import datetime

MAX_SPEED_KMH = 80.0
KM_PER_DEG_LAT = 111.32


@dataclass(frozen=True)
class BBox:
    lat_min: float
    lat_max: float
    lon_min: float
    lon_max: float


HCMC_BBOX = BBox(lat_min=10.65, lat_max=10.90, lon_min=106.55, lon_max=106.85)


@dataclass(frozen=True)
class Ping:
    vehicle_id: str
    event_ts: datetime
    lat: float
    lon: float
    speed_kmh: float
    heading_deg: float

    def to_dict(self) -> dict[str, object]:
        return {
            "vehicle_id": self.vehicle_id,
            "event_ts": self.event_ts.strftime("%Y-%m-%dT%H:%M:%S.")
            + f"{self.event_ts.microsecond // 1000:03d}Z",
            "lat": self.lat,
            "lon": self.lon,
            "speed_kmh": self.speed_kmh,
            "heading_deg": self.heading_deg,
        }
